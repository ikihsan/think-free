#!/usr/bin/env python3
"""G0 - instrument discrimination, run before any population row is read.

Three arms, every label known by construction (PROTOCOL.md, G0):

  positive  20 well-known module names whose providing distribution has a
            different name. The index must name the right project >= 18.
  negative  30 module names of things that do not exist. The index must
            resolve 0 of them.
  forward   E085's own positive controls, read from its committed results.
            The forward direction must recover >= 8 of 10.

The positive arm's list is written here as (module, expected project) pairs, so
a reader can check each answer against the wheel's own central directory rather
than against the tool that produced it: every expectation below is a fact about
PyPI that was true before this file existed.

status: draft. Run: python3 g0_discrimination.py
"""

import json
import os
import sys
import time
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(
    os.path.join(HERE, os.pardir, os.pardir, "pyprovides")))
from pyprovides import provides, pypi, _pick_wheel, _central_directory, \
    entry_names, top_level_modules   # noqa: E402

# Module name -> the distribution a developer is actually looking for.
POSITIVE = [
    ("bs4", "beautifulsoup4"),
    ("cv2", "opencv-python"),
    ("PIL", "pillow"),
    ("sklearn", "scikit-learn"),
    ("Crypto", "pycryptodome"),
    ("dateutil", "python-dateutil"),
    ("dotenv", "python-dotenv"),
    ("zmq", "pyzmq"),
    ("OpenGL", "PyOpenGL"),
    ("serial", "pyserial"),
    ("MySQLdb", "mysqlclient"),
    ("psycopg2", "psycopg2-binary"),
    ("yaml", "PyYAML"),
    ("jwt", "PyJWT"),
    ("usb", "pyusb"),
    ("attr", "attrs"),
    ("win32api", "pywin32"),
    ("Tkinter", "tk"),
    ("fitz", "PyMuPDF"),
    ("docx", "python-docx"),
    ("lxml", "lxml"),
]

# Things that do not exist. Each is a plausible top-level import that no
# distribution ships. Generated by prefixing a real-looking stem with a token
# no project uses, so a resolver that answers from string shape rather than from
# a wheel's file list is caught.
NEGATIVE = ["zzq_%d" % i for i in range(30)]

# E085's forward controls: a distribution, and a module it is known to ship.
FORWARD = [
    ("numpy", "numpy"), ("requests", "requests"), ("pandas", "pandas"),
    ("matplotlib", "matplotlib"), ("scipy", "scipy"), ("yaml", "yaml"),
    ("Pillow", "PIL"), ("beautifulsoup4", "bs4"), ("pyzmq", "zmq"),
    ("PyMySQL", "pymysql"),
]


def normalize(name):
    """PEP 503 normalisation - the same rule pip applies before installing."""
    import re
    return re.sub(r"[-_.]+", "-", name).lower()


def build_index(names, workers=16, cache_dir=None):
    """module -> [projects], read from each project's wheel central directory."""
    cache_dir = cache_dir or os.path.join(HERE, "cache-g0")
    index, statuses = {}, {}

    def one(name):
        t0 = time.time()
        try:
            ok, payload = pypi(name)
            if not ok:
                return name, "no-such-project", [], round(time.time() - t0, 2)
            wheel = _pick_wheel(payload)
            if wheel is None:
                return name, "no-wheel", [], round(time.time() - t0, 2)
            _total, cd = _central_directory(wheel["url"], wheel.get("size"))
            mods = top_level_modules(entry_names(cd))
            return name, "ok", sorted(mods), round(time.time() - t0, 2)
        except Exception as exc:                       # noqa: BLE001
            return name, "read-error:%s" % type(exc).__name__, [], \
                round(time.time() - t0, 2)

    with ThreadPoolExecutor(workers) as ex:
        rows = list(ex.map(one, names))
    for name, status, mods, _secs in rows:
        statuses[name] = status
        for m in mods:
            index.setdefault(m, []).append(name)
    return index, statuses, {m: sorted(set(v)) for m, v in index.items()}


def main():
    projects = sorted({p for _m, p in POSITIVE} | {p for p, _m in FORWARD})
    started = time.time()
    index, statuses, _ = build_index(projects)
    build_s = round(time.time() - started, 1)

    pos_rows = []
    for module, expected in POSITIVE:
        got = index.get(module, [])
        pos_rows.append({"module": module, "expected": expected,
                         "got": got, "correct": expected in got})

    neg_rows = []
    for module in NEGATIVE:
        got = index.get(module, [])
        neg_rows.append({"module": module, "got": got, "resolved": bool(got)})

    fwd_rows = []
    for project, module in FORWARD:
        status, mods, _detail = provides(project, cache_dir=os.path.join(
            HERE, "cache-g0"))
        fwd_rows.append({"project": project, "module": module,
                         "status": status, "recovered": module in mods})

    pos_ok = sum(r["correct"] for r in pos_rows)
    neg_hit = sum(r["resolved"] for r in neg_rows)
    fwd_ok = sum(r["recovered"] for r in fwd_rows)

    result = {
        "schema": "e090.g0/1",
        "n_projects_read": len(projects),
        "index_size": len(index),
        "build_seconds": build_s,
        "arm_positive": {"n": len(pos_rows), "resolved_correct": pos_ok,
                         "threshold": 18, "rows": pos_rows},
        "arm_negative": {"n": len(neg_rows), "resolved": neg_hit,
                         "threshold": 0, "rows": neg_rows},
        "arm_forward": {"n": len(fwd_rows), "recovered": fwd_ok,
                        "threshold": 8, "rows": fwd_rows},
        "status_counts": _counts(statuses),
        "g0": "PASS" if (pos_ok >= 18 and neg_hit == 0 and fwd_ok >= 8)
              else "FAIL",
    }
    with open(os.path.join(HERE, "g0-results.json"), "w") as fh:
        json.dump(result, fh, indent=1, sort_keys=True)
    print(json.dumps({k: v for k, v in result.items() if k != "arm_positive"},
                     indent=1, sort_keys=True))
    print("positive failures:",
          [(r["module"], r["expected"], r["got"]) for r in pos_rows
           if not r["correct"]])
    return 0 if result["g0"] == "PASS" else 3


def _counts(values):
    out = {}
    for v in values.values():
        out[v] = out.get(v, 0) + 1
    return out


if __name__ == "__main__":
    sys.exit(main())