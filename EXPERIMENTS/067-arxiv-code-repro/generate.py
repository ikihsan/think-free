#!/usr/bin/env python3
"""
E067 — Environment Spec Generator from Partial Information.

Generates pinned environment specifications (requirements.txt, environment.yml,
Dockerfile) from partial information: README + unpinned dependencies + import
statements in Python files, for repositories that have NO working environment
specification at all.

This addresses the precise gap identified in E067: all existing tools (pip-tools,
poetry, uv, conda-lock, Binder, Codespaces) require a working environment or
run existing specs. None generate a runnable, pinned environment specification
from partial information for a repository that has no working environment.
"""
import re
import os
import sys
import json
import urllib.request
from typing import List, Set, Dict, Optional, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))


def extract_packages_from_readme(readme_path: str) -> Set[str]:
    """Extract package names from README install instructions."""
    packages = set()
    if not os.path.exists(readme_path):
        return packages
    with open(readme_path, "r", encoding="utf-8", errors="replace") as f:
        content = f.read()
    # Look for pip install commands
    for line in content.split("\n"):
        # Match: pip install pkg1 pkg2 (capture everything after pip install)
        m = re.findall(r"pip\s+install\s+(.+)", line, re.IGNORECASE)
        for mm in m:
            for pkg in mm.split():
                pkg = pkg.strip(".,;:!" " '\"()[]")
                # Filter out common non-package words
                if pkg.lower() in {
                    "the", "and", "or", "but", "if", "then", "else",
                    "install", "requirements", "dependencies", "python",
                    "version", "latest", "see", "more", "documentation"
                }:
                    continue
                # Keep alphanumeric + hyphen/underscore packages
                if re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]*$", pkg):
                    packages.add(pkg.lower())
    return packages


# Build-in module names that should not be included as dependencies
_BUILTIN_MODULES = {
    "abc", "aifc", "argparse", "array", "ast", "asyncio", "base64",
    "binascii", "bisect", "calendar", "csv", "datetime", "dbm",
    "decimal", "email", "enum", "faulthandler", "fileinput",
    "float", "fpectrl", "frozenimportlib", "importlib", "json",
    "math", "multiprocessing", "operator", "os", "pathlib",
    "pickle", "platform", "poplib", "re", "secrets", "signal",
    "socket", "stat", "string", "struct", "subprocess",
    "sys", "tempfile", "threading", "time", "traceback",
    "types", "uuid", "weakref", "xml"
}

def _is_builtin(pkg_name: str) -> bool:
    """Check if a package name is a Python built-in module."""
    return pkg_name.lower() in _BUILTIN_MODULES

def extract_packages_from_imports(python_dir: str) -> Set[str]:
    """Extract package names from Python import statements."""
    packages = set()
    if not os.path.isdir(python_dir):
        return packages
    for root, dirs, files in os.walk(python_dir):
        for fname in files:
            if fname.endswith(".py"):
                fpath = os.path.join(root, fname)
                try:
                    with open(fpath, "r", encoding="utf-8", errors="replace") as f:
                        for line in f:
                            # Match: import pkg or from pkg import ...
                            m1 = re.match(r"^import\s+([A-Za-z0-9._-]+)", line.strip())
                            if m1:
                                pkg = m1.group(1).split(".")[0]
                                if not _is_builtin(pkg):
                                    packages.add(pkg.lower())
                            m2 = re.match(r"^from\s+([A-Za-z0-9._-]+)\s+import", line.strip())
                            if m2:
                                pkg = m2.group(1).split(".")[0]
                                if not _is_builtin(pkg):
                                    packages.add(pkg.lower())
                except Exception:
                    continue
    return packages


def fetch_latest_version(package_name: str) -> Optional[str]:
    """Fetch the latest version of a package from PyPI."""
    try:
        url = f"https://pypi.org/pypi/{package_name}/json"
        req = urllib.request.Request(url, headers={"User-Agent": "E067-gen/1.0"})
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.load(resp)
            return data["info"]["version"]
    except Exception:
        return None


def generate_requirements_txt(packages: Set[str]) -> str:
    """Generate a requirements.txt with latest pinned versions."""
    lines = ["# Generated by E067 environment spec generator"]
    lines.append("# Generated from partial information: README + import statements")
    lines.append("")
    # Sort packages alphabetically for reproducibility
    for pkg in sorted(packages):
        version = fetch_latest_version(pkg)
        if version:
            lines.append(f"{pkg}=={version}")
        else:
            # If we can't fetch the version, include without version pin
            lines.append(pkg)
    lines.append("")
    return "\n".join(lines)


def generate_environment_yml(packages: Set[str]) -> str:
    """Generate a conda environment.yml with latest versions."""
    lines = ["name: e067-generated-env", "channels:", "  - defaults"]
    lines.append("dependencies:")
    # Add Python first
    lines.append("  - python=3.11")
    for pkg in sorted(packages):
        version = fetch_latest_version(pkg)
        if version:
            # Handle conda package names that differ from PyPI names
            conda_name = pkg
            lines.append(f"  - {conda_name}={version}")
        else:
            lines.append(f"  - {pkg}")
    lines.append("  - pip")
    lines.append("  - pip:")
    # Also add pip-installed packages with versions
    for pkg in sorted(packages):
        version = fetch_latest_version(pkg)
        if version:
            lines.append(f"    - {pkg}=={version}")
    return "\n".join(lines)


def generate_dockerfile(packages: Set[str], base_image: str = "python:3.11-slim") -> str:
    """Generate a Dockerfile with the given packages."""
    lines = [
        f"FROM {base_image}",
        "WORKDIR /app",
        "COPY . /app",
    ]
    # Install packages
    if packages:
        pkg_lines = " ".join(f"{pkg}=={fetch_latest_version(pkg) or ''}" for pkg in sorted(packages) if fetch_latest_version(pkg))
        if pkg_lines:
            lines.append(f"RUN pip install --no-cache-dir {pkg_lines}")
    lines.append("COPY . /app")
    lines.append("CMD [\"python\", \"-u\", \"main.py\"]")
    return "\n".join(lines)


def guess_repo_name(repo_path: str) -> Optional[str]:
    """Guess the repo name from its path or structure."""
    basename = os.path.basename(repo_path.rstrip("/"))
    if basename:
        return basename
    return None


def generate_spec(repo_path: str) -> Dict[str, str]:
    """Generate all three spec types from a repo with no working environment."""
    result = {}
    
    # Extract packages from README and imports
    readme_path = os.path.join(repo_path, "README.md")
    readme_pkgs = extract_packages_from_readme(readme_path)
    
    # Find Python source files
    py_dir = os.path.join(repo_path, "src") or repo_path
    import_pkgs = extract_packages_from_imports(py_dir)
    
    # Combine all packages
    all_pkgs = readme_pkgs | import_pkgs
    
    if all_pkgs:
        result["requirements_txt"] = generate_requirements_txt(all_pkgs)
        result["environment_yml"] = generate_environment_yml(all_pkgs)
        result["dockerfile"] = generate_dockerfile(all_pkgs)
    else:
        result["requirements_txt"] = "# No packages detected from partial information"
        result["environment_yml"] = "# No packages detected from partial information"
        result["dockerfile"] = "# No packages detected from partial information"
    
    return result


def test_spec(spec_text: str, test_code: str = 'print("hello")') -> bool:
    """Test if a requirements.txt spec works by installing and importing."""
    import tempfile
    import subprocess
    
    # Write requirements.txt
    with tempfile.NamedTemporaryFile(mode='w', suffix='.txt', delete=False) as f:
        f.write(spec_text)
        req_file = f.name
    
    try:
        # Install
        result = subprocess.run(
            [sys.executable, "-m", "pip", "install", "-q", "-r", req_file],
            capture_output=True, text=True, timeout=120
        )
        if result.returncode != 0:
            return False
        
        # Test import
        result = subprocess.run(
            [sys.executable, "-c", test_code],
            capture_output=True, text=True, timeout=30
        )
        return result.returncode == 0
    except Exception:
        return False
    finally:
        try:
            os.unlink(req_file)
        except:
            pass


# Command-line interface
def main():
    import argparse
    parser = argparse.ArgumentParser(description="E067: Generate env spec from partial info")
    parser.add_argument("repo_path", help="Path to repository with no environment spec")
    parser.add_argument("--test", action="store_true", help="Test generated spec")
    parser.add_argument("--output", help="Output file prefix (defaults to stdout)")
    args = parser.parse_args()
    
    repo_path = args.repo_path
    if not os.path.isdir(repo_path):
        print(f"Error: {repo_path} is not a directory", file=sys.stderr)
        sys.exit(1)
    
    spec = generate_spec(repo_path)
    
    if args.output:
        for key, value in spec.items():
            with open(f"{args.output}.{key}", "w") as f:
                f.write(value)
        print(f"Spec files written with prefix {args.output}")
    else:
        print(f"Repository: {repo_path}")
        print("=" * 60)
        print("\n=== requirements.txt ===")
        print(spec.get("requirements_txt", "N/A"))
        print("\n=== environment.yml ===")
        print(spec.get("environment_yml", "N/A"))
        print("\n=== Dockerfile ===")
        print(spec.get("dockerfile", "N/A"))
    
    if args.test:
        test_code = "import os; import sys; print('success')"
        # Use requirements_txt for testing
        req_text = spec.get("requirements_txt", "")
        if "No packages detected" not in req_text and req_text.strip():
            success = test_spec(req_text, test_code)
            print(f"\nTest {'PASSED' if success else 'FAILED'}: generated spec installs and runs")
        else:
            print("\nTest SKIPPED: no packages detected")


if __name__ == "__main__":
    main()