# ── Load E211 entry survival raw data ──────────────────────────────────────
# Read the results.json generated by the E211 experiment (2026-10-21) to extract
# survival, graduation, and net-positive metrics for each PSC code. Used by the
# two-axis framework to combine accessibility and sustainability metrics.
# Path resolved relative to this script's location, going up to the repository root
# where EXPERIMENTS/ resides.
_E211_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "EXPERIMENTS",
    "E211-entry-survival",
    "raw",
    "results.json",
)

try:
    with open(_E211_PATH, "r") as _f:
        _E211_DATA = json.load(_f)
except (IOError, json.JSONDecodeError):
    _E211_DATA = {}


def load_e211_survival(psc_code: str) -> dict:
    """Load survival/graduation metrics from E211 raw results for a PSC code.

    Parameters
    ----------
    psc_code : str
        PSC code to extract metrics for (e.g. '7030', 'DA10').

    Returns
    -------
    dict with keys: survival (0-1), graduation (0-1), survival_net_positive (0-1),
    n_cohort (int), n_surviving (int), n_graduates (int), mean_awards_per_uei (float or None)
    None if the code's data is not available.
    """
    if not _E211_DATA or "codes" not in _E211_DATA:
        return None

    # Try the requested code, then fall back to known codes
    code_upper = psc_code.upper()
    for code in [code_upper] + ["7030", "DA10", "DA01", "6810"]:
        if code in _E211_DATA["codes"]:
            c = _E211_DATA["codes"][code]
            survival = c.get("survival", 0.0)
            graduation = c.get("graduation", 0.0)
            surv_net_pos = c.get("survival_net_positive", 0.0)
            n_cohort = c.get("cohort_distinct_uei", 0)
            survivors_list = c.get("survivors", [])
            n_surviving = len(survivors_list) if isinstance(survivors_list, list) else 0
            n_graduates = c.get("graduates", 0)

            # Compute mean awards per UEI from survivors list if available
            mean_awards = None
            if survivors_list and isinstance(survivors_list, list) and n_cohort and n_cohort > 0:
                mean_awards = len(survivors_list) / n_cohort

            return {
                "survival": survival,
                "graduation": graduation,
                "survival_net_positive": surv_net_pos,
                "mean_awards_per_uei": mean_awards,
                "n_cohort": n_cohort,
                "n_surviving": n_surviving,
                "n_graduates": n_graduates,
            }
    return None


