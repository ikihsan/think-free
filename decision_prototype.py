def main():
    """Main entry point."""
    if len(sys.argv) < 4:
        print("Usage: python3 decision_prototype.py <BUDGET> <GTM> <FOCUS>")
        print("  BUDGET: leq_40k | leq_100k | enterprise")
        print("  GTM: direct | gsa_mas | services")
        print("  FOCUS: software | services")
        print()
        print("Examples:")
        print("  python3 decision_prototype.py leq_40k direct software")
        print("  python3 decision_prototype.py leq_100k gsa_mas software")
        print("  python3 decision_prototype.py enterprise services services")
        sys.exit(1)

    budget = sys.argv[1]
    gtm = sys.argv[2]
    focus = sys.argv[3]

    # Validate inputs
    valid_budgets = ["leq_40k", "leq_100k", "enterprise"]
    valid_gtms = ["direct", "gsa_mas", "services"]
    valid_focuses = ["software", "services"]

    if budget not in valid_budgets:
        print(f"Error: Budget must be one of {valid_budgets}")
        sys.exit(1)
    if gtm not in valid_gtms:
        print(f"Error: GTM must be one of {valid_gtms}")
        sys.exit(1)
    if focus not in valid_focuses:
        print(f"Error: Focus must be one of {valid_focuses}")
        sys.exit(1)

    # Assess the profile
    result = assess_team_profile(budget, gtm, focus)

    # Print the assessment
    print_assessment(result)


if __name__ == "__main__":
    main()